-- Étape 6: Vérifier si la migration n'a pas déjà été appliquée
DO $$
BEGIN
  -- Si editorial_calendar_old existe déjà, la migration a déjà été lancée
  IF EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public' AND tablename = 'editorial_calendar_old') THEN
    RAISE NOTICE 'Migration déjà partiellement appliquée - editorial_calendar_old existe';
    -- Supprimer la nouvelle table si elle est vide pour recommencer proprement
    IF EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public' AND tablename = 'editorial_calendar') THEN
