-- Étape 7: Créer la nouvelle table avec client_id (si elle n'existe pas)
DROP TABLE IF EXISTS public.editorial_calendar;
CREATE TABLE public.editorial_calendar (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id         BIGINT NOT NULL REFERENCES public.client(id) ON DELETE CASCADE,
  title             TEXT NOT NULL,
  publish_date      DATE NOT NULL,
  publish_time      TIME,
  platform          TEXT NOT NULL DEFAULT 'instagram',
  objective         TEXT NOT NULL DEFAULT 'engagement',
  strategic_intent  TEXT,
  pillar            TEXT NOT NULL,
  persona           TEXT,
  script_id         BIGINT,
  status            TEXT NOT NULL DEFAULT 'idea'
                    CHECK (status IN ('idea', 'production', 'scheduled', 'published')),
  notes             TEXT,
  color             TEXT,
  created_at        TIMESTAMPTZ DEFAULT NOW(),
  updated_at        TIMESTAMPTZ DEFAULT NOW()
);

-- Étape 8: Migrer les données de l'ancienne table vers la nouvelle
-- Récupérer client_id depuis social_media_strategy
INSERT INTO public.editorial_calendar (
  id, client_id, title, publish_date, pillar, platform, objective, status, created_at, updated_at
)
SELECT 
  eco.id,
  sms.client_id,
  COALESCE(eco.name, 'Calendrier migré'),
  COALESCE(eco.start_date, CURRENT_DATE),
  'Général', -- Pilier par défaut pour les anciennes entrées
  'instagram', -- Platform par défaut
  'engagement', -- Objective par défaut
  'idea', -- Status par défaut
  eco.created_at,
  eco.updated_at
FROM public.editorial_calendar_old eco
JOIN public.social_media_strategy sms ON sms.id = eco.strategy_id
WHERE sms.client_id IS NOT NULL
  AND EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public' AND tablename = 'editorial_calendar_old')
ON CONFLICT (id) DO NOTHING;

-- Étape 9: Réinitialiser la séquence d'ID
-- Vérifier quelle séquence est attachée à la colonne
DO $$
DECLARE
  current_max BIGINT;
BEGIN
  -- Récupérer le max ID actuel
  SELECT COALESCE(MAX(id), 0) INTO current_max FROM public.editorial_calendar;
  
  -- Réinitialiser la séquence (essayer les deux noms possibles)
  BEGIN
    PERFORM setval('public.editorial_calendar_id_seq', current_max);
  EXCEPTION WHEN undefined_table THEN
    -- La séquence n'existe pas avec ce nom, essayer l'autre
    BEGIN
      PERFORM setval(pg_get_serial_sequence('public.editorial_calendar', 'id'), current_max);
    EXCEPTION WHEN OTHERS THEN
      RAISE NOTICE 'Impossible de réinitialiser la séquence automatiquement';
    END;
  END;
  
  RAISE NOTICE 'Séquence réinitialisée à %', current_max;
END$$;

